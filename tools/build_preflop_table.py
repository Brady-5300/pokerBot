"""Generate preflop_table.py: each starting hand's percentile, 0.0 = strongest.

Hands are ranked by Monte Carlo equity against two random opponents.
Run from the project root: python tools/build_preflop_table.py
"""

import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from evaluator import RANKS, evaluate

SIMS_PER_HAND = 6000
OPPONENTS = 2


def representative(key):
    high, low = RANKS.index(key[0]), RANKS.index(key[1])
    if len(key) == 2:
        return [high << 2, low << 2 | 1], 6
    if key[2] == "s":
        return [high << 2, low << 2], 4
    return [high << 2, low << 2 | 1], 12


def all_keys():
    keys = []
    for high in range(12, -1, -1):
        for low in range(high, -1, -1):
            if high == low:
                keys.append(RANKS[high] * 2)
            else:
                keys.append(RANKS[high] + RANKS[low] + "s")
                keys.append(RANKS[high] + RANKS[low] + "o")
    return keys


def equity(hole, rng):
    deck = [card for card in range(52) if card not in hole]
    total = 0.0
    for _ in range(SIMS_PER_HAND):
        dealt = rng.sample(deck, 5 + OPPONENTS * 2)
        board = dealt[:5]
        mine = evaluate(hole + board)
        best = mine
        ties = 1
        for seat in range(OPPONENTS):
            start = 5 + seat * 2
            theirs = evaluate(dealt[start:start + 2] + board)
            if theirs > best:
                best, ties = theirs, 1
            elif theirs == best:
                ties += 1
        if mine == best:
            total += 1.0 / ties
    return total / SIMS_PER_HAND


def main():
    rng = random.Random(20261109)
    rows = []
    for key in all_keys():
        hole, combos = representative(key)
        rows.append((equity(hole, rng), key, combos))
    rows.sort(reverse=True)

    seen = 0
    lines = []
    for value, key, combos in rows:
        # Midpoint of the hand's slice of the 1326 possible combos.
        lines.append(f'    "{key}": {(seen + combos / 2) / 1326:.4f},  # equity {value:.3f}')
        seen += combos

    body = "\n".join(lines)
    (ROOT / "preflop_table.py").write_text(
        '"""Generated by tools/build_preflop_table.py. Do not edit by hand."""\n\n'
        f"PERCENTILE = {{\n{body}\n}}\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
